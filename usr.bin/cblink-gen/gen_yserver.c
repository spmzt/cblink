/*
 * A server's handler table of YANG modules (-m server, PLAN-SDN-YANG
 * 1.6.6): base_server.c, the cbl_yserver the library serves the modules
 * by, its entries by SID, each the program's handlers for one node
 * behind adapters of the library's types: the get and edit of each
 * top-level data node, each rpc's and each action's.
 */

#include <inttypes.h>
#include <stdlib.h>
#include <string.h>

#include "gen.h"
#include "schema.h"

struct ysrv {
	struct buf	 adapters;
	struct entry {
		uint64_t	 sid;
		char		*text;
	}		*v;
	size_t		 n;
	struct diags	*d;
};

static void
entry(void *arg, enum yc_handler kind, const struct snode *n,
    const struct smodule *m)
{
	struct ysrv *y = arg;
	struct buf fn, in, out, md, e;
	size_t k = y->n;

	if (kind == YH_NOTIF)
		return;
	if (n->sid == 0) {
		diag_add(y->d, 0, 0, "%s:%s: no SID: its module's .sid file "
		    "(-s) gives it one", n->module->name, n->name);
		return;
	}
	buf_init(&fn);
	buf_init(&in);
	buf_init(&out);
	buf_init(&md);
	buf_init(&e);
	yc_struct(&fn, n);
	switch (kind) {
	case YH_DATA:
		yc_mangle(&md, m->name);
		buf_printf(&y->adapters, "static int\nh%zu_get(cbl_req *r, void "
		    "*data, cbl_yarena *a)\n{\n\n\treturn (%s_get(r, data, a));"
		    "\n}\n\n", k, fn.p);
		buf_printf(&e, "\t{ UINT64_C(%" PRIu64 "), h%zu_get, ", n->sid,
		    k);
		if (n->flags & SNF_CONFIG) {
			buf_printf(&y->adapters, "static int\nh%zu_edit(cbl_req "
			    "*r, const void *before, const void *after)\n{\n\n"
			    "\treturn (%s_edit(r, before, after));\n}\n\n", k,
			    fn.p);
			buf_printf(&e, "h%zu_edit, NULL, NULL },\n", k);
		} else
			buf_puts(&e, "NULL, NULL, NULL },\n");
		break;
	case YH_RPC:
		buf_printf(&y->adapters, "static int\nh%zu_rpc(cbl_req *r, const "
		    "void *in, void *out, cbl_yarena *a)\n{\n\n\treturn "
		    "(%s_rpc(r, in, out, a));\n}\n\n", k, fn.p);
		buf_printf(&e, "\t{ UINT64_C(%" PRIu64 "), NULL, NULL, "
		    "h%zu_rpc, NULL },\n", n->sid, k);
		break;
	case YH_ACTION:
		buf_printf(&y->adapters, "static int\nh%zu_action(cbl_req *r, "
		    "const struct cbl_bytes *target,\n    const void *in, void "
		    "*out, cbl_yarena *a)\n{\n\n\treturn (%s_action(r, target, "
		    "in, out, a));\n}\n\n", k, fn.p);
		buf_printf(&e, "\t{ UINT64_C(%" PRIu64 "), NULL, NULL, NULL, "
		    "h%zu_action },\n", n->sid, k);
		break;
	case YH_NOTIF:
		break;
	}
	y->v = xreallocarray(y->v, y->n + 1, sizeof(*y->v));
	y->v[y->n].sid = n->sid;
	y->v[y->n++].text = e.p;
	buf_free(&fn);
	buf_free(&in);
	buf_free(&out);
	buf_free(&md);
}

static int
entry_cmp(const void *a, const void *b)
{
	const struct entry *x = a, *y = b;

	return ((x->sid > y->sid) - (x->sid < y->sid));
}

int
gen_yang_server(struct schema *s, const char *base, const char *from,
    const struct ysidcbor *sids, size_t nsids, struct buf *out,
    struct diags *d)
{
	struct ysrv y = { .d = d };
	struct buf nm;
	size_t errs = d->n;

	buf_init(&y.adapters);
	yc_handlers(s, entry, &y);
	qsort(y.v, y.n, sizeof(*y.v), entry_cmp);
	buf_init(&nm);
	yc_mangle(&nm, base);
	buf_printf(out, "/*\n * Generated by cblink-gen %s from %s.  Do not "
	    "edit.\n *\n * The server's handlers, by SID (cbl_schema.h): %zu "
	    "nodes'.\n */\n\n#include <stddef.h>\n#include <stdint.h>\n\n"
	    "#include <cbl_schema.h>\n\n#include \"%s.h\"\n\n", CBLGEN_VERSION,
	    from, y.n, base);
	if (y.adapters.len > 0)
		buf_puts(out, y.adapters.p);
	buf_puts(out, "static const struct cbl_yhandler handlers[] = {\n");
	for (size_t i = 0; i < y.n; i++) {
		buf_puts(out, y.v[i].text);
		free(y.v[i].text);
	}
	if (y.n == 0)
		buf_puts(out, "\t{ 0, NULL, NULL, NULL, NULL },\n");
	buf_puts(out, "};\n");
	/* The .sid files given, for GET-SID: ietf-sid-file's value. */
	for (size_t i = 0; i < nsids; i++) {
		buf_printf(out, "\n/* %s's .sid file. */\nstatic const uint8_t "
		    "sid%zu[] = {", sids[i].module, i);
		for (size_t k = 0; k < sids[i].cbor.len; k++)
			buf_printf(out, "%s0x%02x,", k % 12 == 0 ? "\n\t" : " ",
			    (unsigned char)sids[i].cbor.p[k]);
		buf_puts(out, "\n};\n");
	}
	if (nsids > 0) {
		buf_puts(out, "\nstatic const struct cbl_ysidfile sidfiles[] = "
		    "{\n");
		for (size_t i = 0; i < nsids; i++) {
			/* A YANG identifier and a date: nothing to escape. */
			buf_printf(out, "\t{ \"%s\", ", sids[i].module);
			if (sids[i].revision != NULL)
				buf_printf(out, "\"%s\"", sids[i].revision);
			else
				buf_puts(out, "NULL");
			buf_printf(out, ", sid%zu, sizeof(sid%zu) },\n", i, i);
		}
		buf_puts(out, "};\n");
	}
	buf_printf(out, "\nextern const struct cbl_yserver %s_server;\n"
	    "const struct cbl_yserver %s_server = {\n\t.schema = &%s_schema,\n"
	    "\t.nhandler = %zu,\n\t.handler = handlers,\n", nm.p, nm.p,
	    nm.p, y.n);
	if (nsids > 0)
		buf_printf(out, "\t.nsidfile = %zu,\n\t.sidfile = sidfiles,\n",
		    nsids);
	buf_puts(out, "};\n");
	free(y.v);
	buf_free(&y.adapters);
	buf_free(&nm);
	return (d->n > errs ? -1 : 0);
}
